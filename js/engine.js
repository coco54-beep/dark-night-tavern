function cancelTurn(){
  if(!activeTurn) return;
  const {controller} = activeTurn;
  activeTurn = null;
  controller.abort();
}

function clearIdleTimer(){
  if(idleTimer){ clearTimeout(idleTimer); idleTimer = null; }
  if(idleRaf){ cancelAnimationFrame(idleRaf); idleRaf = null; }
  const bar = $("idle-bar");
  if(bar) bar.hidden = true;
}

function stopStoryForIdle(){
  if(!S || !S.ai || S.ending) return;
  clearIdleTimer();
  S.ending = {
    good:false,
    title:"沉默超时",
    note:"— 连续两次 90 秒没有回应，故事停止 —",
    text:"你两次没有回应。灯火渐暗，酒馆里的声音慢慢远去，这一夜的故事停在了这里。"
  };
  saveProgress();
  showEndingAI(S.ending);
}

function armIdleTimer(){
  clearIdleTimer();
  if(!S.ai || S.ending) return;
  if((S.idleCount||0)>=2){
    stopStoryForIdle();
    return;
  }
  const secs = S.idleTimeout || 90;
  const duration = secs*1000;
  let remaining = duration;
  let lastTick = Date.now();
  const bar = $("idle-bar");
  const input = $("action-text");
  if(bar){ bar.hidden = false; }
  const tick = ()=>{
    const now = Date.now();
    const composing = document.activeElement===input || input.value.trim()!=="";
    // 跳过页面暂停或切到后台时经过的时间。
    const elapsed = Math.max(0, now-lastTick);
    if(!document.hidden && !composing && elapsed<=1000){
      remaining = Math.max(0,remaining-elapsed);
    }
    lastTick = now;
    const fill = $("idle-fill"), label = $("idle-label");
    if(fill) fill.style.width = (remaining/duration*100) + "%";
    if(label) label.textContent = composing ? "输入时暂停倒计时"
      : Math.ceil(remaining/1000) + " 秒后，剧情将自行推进……";
    if(remaining<=0){ clearIdleTimer(); triggerIdle(); return; }
    idleRaf = requestAnimationFrame(tick);
  };
  tick();
}

function triggerIdle(){
  if(!S.ai || S.ending || activeTurn) return;
  if((S.idleCount||0)>=1){ stopStoryForIdle(); return; }
  const choice = { text:"（沉默）", idle:true, speech:true };
  aiTurn(choice);
}

