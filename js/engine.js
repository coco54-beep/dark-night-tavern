function isGenericChoice(text){
  return /^(继续|继续剧情|问问情况|询问情况|离开|等等)[。！？!？\s]*$/.test(text);
}

function isPaymentInquiry(choice){
  if(!choice?.speech || choice.idle) return false;
  const text = choice.text;
  return /差价|房钱|价钱|价格|报价|多少钱|几文|几块|怎么付|如何付|还能便宜|能不能便宜/.test(text)
    && /[？?]|还有什么办法|先问问|只问/.test(text)
    && !/[（(【[]|我(?:这就|现在|愿意|已经)?(?:付|交|给|买|订|赊|同意|接受|成交)/.test(text);
}

function keepsOriginal(choice){
  return choice?.speech && !choice.idle
    && /(?:原件|原本|收据|单据).{0,24}(?:留在我手|留在自己手|不离手|不交|不递|我自己拿|我得拿着)/.test(choice.text);
}

function custodyProblem(scene,choice){
  if(!keepsOriginal(choice)) return "";
  const text = scene.lines.map(line=>line.text).join("\n");
  if(/(?:接过|接住)你(?:递|交)|你(?:便|就|随即|于是|先|直接)?(?:把|将)(?:手里的|手中的|那份|这份|那张|这张)?(?:原件|原本|收据|单据)(?:递给|递过去|递去|交给|交出去)|你(?:便|就|随即|于是|先|直接)?(?:递出|递去|交出)(?:了)?(?:原件|原本|收据|单据)/.test(text)){
    return "玩家明确要求保留原件。不能写玩家已将原件递交给别人，请让 NPC 提出举着核对、抄副本或证人作证等办法。";
  }
  return "";
}

function requiresFullTurnContext(state,choice){
  if(!state.turn || choice?.offerId || choice?.skill || choice?.attr || choice?.tradeoff) return true;
  if(isPaymentInquiry(choice)) return true;
  if((state.consequences||[]).some(c=>c.status==="pending" || state.turn-c.turn<=4)) return true;
  const deadlines = (state.plot?.conflict||"")+" "+(state.plot?.next||"");
  return /限时|截止|关柜|打烊|换班|倒计时|还剩|来不及|(?:[零一二两三四五六七八九十]{1,3}|\d{1,2})(?:点|时|:\d\d)/.test(deadlines);
}

