function extractJSON(text){
  let clean = String(text).trim();
  // 去掉可能存在的 markdown 围栏（开头/结尾，含流式未闭合的围栏）
  clean = clean.replace(/^```(?:json)?\s*/i,"").replace(/```\s*$/,"");
  const i = clean.indexOf("{"), j = clean.lastIndexOf("}");
  const body = i>=0 && j>i ? clean.slice(i,j+1) : clean;
  try{ return JSON.parse(body); }catch(e){}
  // 容错 1：去掉对象/数组内的尾逗号
  const noTrailing = body.replace(/,\s*([}\]])/g,"$1");
  try{ return JSON.parse(noTrailing); }catch(e){}
  // 容错 2：逐字符扫描，处理字符串截断与未闭合的括号/数组（按栈补全）
  function repair(src){
    let out = "";
    const stack = [];
    let inStr = false, esc = false;
    for(const ch of src){
      out += ch;
      if(inStr){
        if(esc){ esc = false; }
        else if(ch==="\\"){ esc = true; }
        else if(ch==="\""){ inStr = false; }
      }else{
        if(ch==="\""){ inStr = true; }
        else if(ch==="{"){ stack.push("}"); }
        else if(ch==="["){ stack.push("]"); }
        else if(ch==="}"||ch==="]"){ if(stack[stack.length-1]===ch) stack.pop(); }
      }
    }
    // 字符串未闭合：若结尾悬空反斜杠则先转义它自身，再补一个引号
    if(inStr){ if(esc) out += "\\"; out += "\""; }
    // 去掉末尾悬空的逗号/冒号（截断常见）
    out = out.replace(/[,\s]+$/,"").replace(/:\s*$/,'');
    // 按栈逆序补全括号
    while(stack.length) out += stack.pop();
    return out;
  }
  const repaired = repair(noTrailing);
  try{ return JSON.parse(repaired); }catch(e){}
  // 容错 2b：清理字符串内的非法转义（如 \U、\ 后跟非合法转义字符）
  const sanitize = s => s.replace(/\\(?!["\\/bfnrtu])/g,"\\\\");
  try{ return JSON.parse(sanitize(repaired)); }catch(e){}
  // 容错 3：对修复版再去一次尾逗号
  try{ return JSON.parse(sanitize(repaired).replace(/,\s*([}\]])/g,"$1")); }catch(e){}
  // 容错 4：尝试截到最后一个完整的对象/数组闭合处再补全
  try{
    const lastBrace = Math.max(body.lastIndexOf("}"), body.lastIndexOf("]"));
    if(lastBrace > 0){
      const partial = repair(body.slice(0, lastBrace+1));
      return JSON.parse(partial.replace(/,\s*([}\]])/g,"$1"));
    }
  }catch(e){}
  throw new Error("剧情格式无法解析，请重试");
}

function parseProseScene(raw){
  let text = String(raw || "").trim();
  if(!text) return null;
  // 去掉 markdown 代码围栏
  text = text.replace(/^```[a-z]*\s*/i, "").replace(/```\s*$/i, "").trim();
  // 定位「选项」区块（兼容 **选项：** / 选项: / 你可以： 等）
  const optMatch = text.match(/\n\s*(?:\*\*)?\s*(?:选项|可选|你的选择|你可以)\s*(?:\*\*)?\s*[:：]?/);
  let body = text, optBlock = "";
  if(optMatch && optMatch.index !== undefined){
    body = text.slice(0, optMatch.index).trim();
    optBlock = text.slice(optMatch.index + optMatch[0].length);
  } else {
    // 没有标题时，尝试从第一个「1.」编号行起切分
    const numStart = text.search(/\n\s*1[\.、．)]\s+\S/);
    if(numStart > 0){ body = text.slice(0, numStart).trim(); optBlock = text.slice(numStart); }
  }
  body = body.replace(/\*\*/g, "").trim();
  if(!body) return null;
  // 解析编号选项
  const choices = [];
  const lines = optBlock.split("\n");
  for(let line of lines){
    line = line.replace(/\*\*/g, "").trim();
    const m = line.match(/^\d+\s*[\.、．)]\s*(.+)$/);
    if(!m) continue;
    let t = m[1].trim();
    let tradeoff = "";
    const sep = t.split(/\s*[—–-]{1,2}\s*/);
    if(sep.length >= 2){ t = sep[0].trim(); tradeoff = sep.slice(1).join(" — ").trim(); }
    // 去掉可能的结尾标点
    t = t.replace(/[。；;]\s*$/, "");
    if(t) choices.push({ text: t.slice(0, 200), ...(tradeoff ? { tradeoff: tradeoff.slice(0, 120) } : {}) });
    if(choices.length >= 4) break;
  }
  if(!body && !choices.length) return null;
  return {
    narration: body.slice(0, 1200),
    choices: choices.length ? choices : [{ text: "继续" }],
    beats: [],
    present: undefined,
    characters: []
  };
}

